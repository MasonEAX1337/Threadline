import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const manifest = JSON.parse(
  await readFile(path.join(root, ".project/manifest.json"), "utf8"),
);
async function records(folder, type, exportName) {
  const files = (await readdir(path.join(root, ".project", folder))).filter(
    (f) => f.endsWith(".json"),
  );
  const order = manifest.order[folder] ?? [];
  files.sort((a, b) => {
    const ai = order.indexOf(a.replace(/\.json$/, ""));
    const bi = order.indexOf(b.replace(/\.json$/, ""));
    return (ai < 0 ? 999 : ai) - (bi < 0 ? 999 : bi) || a.localeCompare(b);
  });
  const imports = files
    .map((f, i) => `import record${i} from "../../.project/${folder}/${f}";`)
    .join("\n");
  return `// Generated by npm run knowledge:sync. Edit .project/${folder}/ records instead.\nimport type { ${type} } from "@/types";\n${imports}\nexport const ${exportName}: ${type}[] = [${files.map((_, i) => `record${i} as ${type}`).join(", ")}];\n`;
}
await writeFile(
  path.join(root, "src/mock/components.ts"),
  (await records("components", "ArchitectureNode", "nodes")) +
    `\nimport architecture from "../../.project/architecture.json";\nimport type { ArchitectureEdge } from "@/types";\nexport const edges = architecture.edges as ArchitectureEdge[];\n`,
);
await writeFile(
  path.join(root, "src/mock/board.ts"),
  await records("tasks", "Task", "tasks"),
);
await writeFile(
  path.join(root, "src/mock/activity.ts"),
  await records("changes", "Change", "changes"),
);
await writeFile(
  path.join(root, "src/mock/architecture.ts"),
  `import architecture from "../../.project/architecture.json";\nimport type { ArchitectureFlow } from "@/types";\nexport const flows = architecture.flows as ArchitectureFlow[];\n`,
);
const baseFiles = [
  ["project", "Project"],
  ["projects", null],
  ["developers", "Developer[]"],
  ["milestones", "Milestone[]"],
  ["notifications", "Notification[]"],
];
let projectFile = `// Generated by npm run knowledge:sync. The repository records are the source of truth.\nimport type { Project, Developer, Milestone, Decision, Notification, OverviewData } from "@/types";\n`;
for (const [file, type] of baseFiles) {
  projectFile += `import ${file}Data from "../../.project/${file}.json";\nexport const ${file} = ${file}Data${type ? ` as ${type}` : ""};\n`;
}
const decisionCode = await records("decisions", "Decision", "decisions");
projectFile += decisionCode.replace(
  'import type { Decision } from "@/types";\n',
  "",
);
projectFile +=
  '\nimport manifestData from "../../.project/manifest.json";\nexport const knowledge = manifestData;\n';
projectFile +=
  '\nimport overviewData from "../../.project/overview.json";\nexport const overview = overviewData as OverviewData;\n';
await writeFile(path.join(root, "src/mock/project.ts"), projectFile);
console.log("Synced repository knowledge into typed frontend adapters.");
